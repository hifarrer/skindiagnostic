#!/usr/bin/env node
/**
 * Patch script to fix expo-router route discovery for Metro web builds
 * This creates an explicit context file with all routes listed
 */
const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const appDir = path.join(projectRoot, 'app');
const expoRouterPath = path.join(projectRoot, 'node_modules', 'expo-router');

console.log('Patch script: Project root:', projectRoot);
console.log('Patch script: App directory:', appDir);

// Find all route files in the app directory
function findRouteFiles(dir, basePath = '.') {
  const routes = [];
  const items = fs.readdirSync(dir, { withFileTypes: true });
  
  for (const item of items) {
    const itemPath = path.join(dir, item.name);
    const routePath = path.join(basePath, item.name);
    
    if (item.isDirectory()) {
      // Recursively search directories
      routes.push(...findRouteFiles(itemPath, routePath));
    } else if (item.isFile() && /\.(tsx?|jsx?)$/.test(item.name)) {
      // Skip +html.tsx as it's handled separately
      if (item.name === '+html.tsx') continue;
      routes.push(routePath);
    }
  }
  
  return routes;
}

const routeFiles = findRouteFiles(appDir);
console.log('Patch script: Found route files:', routeFiles);

// Generate the context file content
// This creates a require.context-like function that Metro can understand
const contextContent = `// Auto-generated route context for Metro web builds
// Generated by patch-expo-router.js

const routes = {
${routeFiles.map(route => {
  const key = './' + route.replace(/\\/g, '/');
  const requirePath = '../../app/' + route.replace(/\\/g, '/');
  return `  '${key}': () => require('${requirePath}'),`;
}).join('\n')}
};

function createContext() {
  const ctx = function(id) {
    const normalizedId = id.replace(/\\.tsx?$/, '');
    const withExt = id;
    
    // Try exact match first
    if (routes[withExt]) return routes[withExt]();
    if (routes[normalizedId + '.tsx']) return routes[normalizedId + '.tsx']();
    if (routes[normalizedId + '.ts']) return routes[normalizedId + '.ts']();
    if (routes[normalizedId + '.js']) return routes[normalizedId + '.js']();
    if (routes[normalizedId + '.jsx']) return routes[normalizedId + '.jsx']();
    
    // Try with normalized path
    for (const key of Object.keys(routes)) {
      if (key.replace(/\\.tsx?$/, '') === normalizedId) {
        return routes[key]();
      }
    }
    
    throw new Error('Cannot find module "' + id + '"');
  };
  
  ctx.keys = function() {
    return Object.keys(routes);
  };
  
  ctx.resolve = function(id) {
    return id;
  };
  
  ctx.id = 'expo-router-context';
  
  return ctx;
}

module.exports = { ctx: createContext() };
`;

// Write the context file to expo-router package
const ctxWebPath = path.join(expoRouterPath, '_ctx.web.js');
console.log('Patch script: Writing context to:', ctxWebPath);
fs.writeFileSync(ctxWebPath, contextContent);
console.log('Patch script: Successfully created route context with', routeFiles.length, 'routes');

// Also create _ctx.js for compatibility
const ctxPath = path.join(expoRouterPath, '_ctx.js');
fs.writeFileSync(ctxPath, contextContent);
console.log('Patch script: Also created _ctx.js');
